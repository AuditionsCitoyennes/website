create function ac.testimonies_derive() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  begin
    new.search_text := ac.fold(new.person_name || ' ' || coalesce(new.person_info, '') || ' '
                               || ac.answers_text(new.content));
    select b.mask, b.approx into new.theme_mask, new.themes_approx from ac.theme_bits(new.topics) b;
    -- !topics?.length (scopeStats.ts): null and empty alike
    new.untagged := coalesce(pg_catalog.cardinality(new.topics), 0) = 0;
    new.derive_version := 1;
  exception when others then
    -- Never block a write: the old app, verify-by-token, the RPCs, the seed.
    new.search_text := null;
    new.theme_mask := null;
    new.themes_approx := null;
    new.untagged := null;
    new.derive_version := -1;
  end;
  return new;
end $$;

