-- Map phase 1, first migration: what the site computes from a
-- testimony's text and tags, kept on the row so the server can count, filter
-- and search without the whole corpus.
--
-- testimonies gains five columns, all filled by one trigger, never by a writer:
--   search_text     fold(person_name || ' ' || person_info || ' ' || answersText(content)),
--                   the haystack of the free-text search (substring, as today);
--   theme_mask      bit i = AUDITION_THEMES[i], themesOf(topics);
--   themes_approx   themesApproximate(topics);
--   untagged        no topics at all (null or empty);
--   derive_version  1 = computed by this file's helpers; -1 = they failed on
--                   this row (the write went through, the columns are null).
--
-- The trigger covers every writer: the old app (still live on this database,
-- writing as authenticated through PostgREST), verify_testimony_by_token with
-- edits, submit_online_testimony, the API, the seed. It is SECURITY DEFINER so
-- that its helpers stay unreachable from anon and authenticated, and it never
-- raises: a helper's failure leaves NULLs and derive_version = -1.
--
-- The helpers live in schema ac, which PostgREST does not expose. Their SQL is
-- generated from @ac/shared (scripts/sql-gen/derived.ts); CI compares their
-- results with the TypeScript over the seed and an edge corpus (npm run db:check).
