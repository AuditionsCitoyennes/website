/**
 * Generates data/DATA_LICENSES.md — the attribution content rendered in the
 * website footer / data page — from data/sources.yml and the download
 * manifest. Do not edit DATA_LICENSES.md by hand; edit sources.yml and re-run
 * "npm run licenses".
 */
import fs from "node:fs";
import { LICENSES_MD } from "./lib/paths.js";
import { loadRegistry } from "./lib/sources.js";
import { loadManifest } from "./lib/manifest.js";

const registry = loadRegistry();
const manifest = loadManifest();

function retrievedDate(sourceId: string): string | null {
  const dates = Object.values(manifest)
    .filter((e) => e.source === sourceId)
    .map((e) => e.retrieved_at.slice(0, 10))
    .sort();
  return dates[dates.length - 1] ?? null;
}

const lines: string[] = [
  "<!-- Generated by data-ingestion/src/gen_licenses.ts — edit data/sources.yml instead. -->",
  "",
  "# Licences et attributions des données",
  "",
  "Ce site affiche, aux côtés des auditions collectées par Auditions Citoyennes,",
  "des jeux de données ouverts d'événements de participation citoyenne comparables.",
  "Chaque source ci-dessous conserve sa licence propre.",
  "",
];

for (const source of registry.sources) {
  const date = retrievedDate(source.id);
  lines.push(`## ${source.name}`);
  lines.push("");
  lines.push(
    `- **Licence** : ${source.license}${source.license_url ? ` (${source.license_url})` : ""}`,
  );
  const attribution = source.attribution.replace("{date}", date ?? "—");
  lines.push(`- **Attribution** : ${attribution}`);
  if (date) lines.push(`- **Extraction** : ${date}`);
  lines.push(
    `- **Publication** : ${
      source.publish
        ? source.non_commercial
          ? "affichage sur sections non monétisées uniquement (NC), données séparées des exports permissifs"
          : "publiable"
        : "affichage avec lien uniquement — licence à confirmer (publish: false)"
    }`,
  );
  lines.push(`- **Données personnelles** : ${source.pii_policy.trim().replace(/\s*\n\s*/g, " ")}`);
  if (source.notes) lines.push(`- **Notes** : ${source.notes.trim().replace(/\s*\n\s*/g, " ")}`);
  lines.push("");
}

lines.push("## Sources explicitement hors périmètre");
lines.push("");
lines.push("Documentées ici pour que de futurs contributeurs ne les réintègrent pas naïvement :");
lines.push("");
for (const excluded of registry.excluded) {
  lines.push(`- **${excluded.name}** — ${excluded.reason}`);
}
lines.push("");

fs.writeFileSync(LICENSES_MD, `${lines.join("\n")}\n`);
console.log(`generated ${LICENSES_MD}`);
