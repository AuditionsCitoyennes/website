// The France poster's pure steps (lib.ts), and the generated module
// (apps/web/src/shared/ui/francePoster.ts) against them: small, metropolitan,
// well-formed. Run with `node --import tsx --test` (root "test:scripts").

import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";
import * as lib from "./lib";
import type { Position, PosterUnit } from "./lib";

const square = (x: number, y: number, s: number): Position[] => [
  [x, y],
  [x + s, y],
  [x + s, y + s],
  [x, y + s],
  [x, y],
];

test("mercatorY is 0 at the equator, grows northwards and is clamped at the poles", () => {
  assert.ok(Math.abs(lib.mercatorY(0)) < 1e-12);
  assert.ok(lib.mercatorY(48) > lib.mercatorY(43));
  assert.equal(lib.mercatorY(90), lib.mercatorY(85.0511));
  assert.ok(Number.isFinite(lib.mercatorY(-90)));
});

test("simplifyLine keeps the ends and the corners past the tolerance only", () => {
  const line: Position[] = [
    [0, 0],
    [1, 0.1],
    [2, 0],
    [3, 5],
    [4, 0],
  ];
  assert.deepEqual(lib.simplifyLine(line, 0.5), [
    [0, 0],
    [2, 0],
    [3, 5],
    [4, 0],
  ]);
  assert.deepEqual(lib.simplifyLine(line, 10), [
    [0, 0],
    [4, 0],
  ]);
  assert.deepEqual(lib.simplifyLine([[1, 1]], 1), [[1, 1]]);
});

test("simplifyRing rounds, drops repeats and the closing point, and drops what is too small", () => {
  const r = lib.simplifyRing(square(0.2, 0.2, 10), 0.5, 1);
  assert.deepEqual(r, [
    [0, 0],
    [10, 0],
    [10, 10],
    [0, 10],
  ]);
  assert.equal(lib.simplifyRing(square(0, 0, 1), 0.1, 2), null);
  assert.equal(
    lib.simplifyRing(
      [
        [0, 0],
        [1, 1],
        [0, 0],
      ],
      0.1,
      0,
    ),
    null,
  );
  assert.equal(Math.abs(lib.ringArea(r!)), 100);
});

test("ringPath writes an absolute move, relative lines and a close", () => {
  assert.equal(
    lib.ringPath([
      [3, 4],
      [5, 4],
      [5, 1],
    ]),
    "M3 4l2 0l0-3z",
  );
});

test("buildPoster keeps the metropolitan régions, north up, inside its box", () => {
  const units: PosterUnit[] = [
    { id: "fr:reg:11", name: "Nord", g: { type: "Polygon", coordinates: [square(2, 48, 1)] } },
    {
      id: "fr:reg:76",
      name: "Sud",
      g: { type: "MultiPolygon", coordinates: [[square(2, 43, 1)], [square(4, 43, 0.001)]] },
    },
    {
      id: "fr:reg:04",
      name: "Outre-mer",
      g: { type: "Polygon", coordinates: [square(55, -21, 1)] },
    },
  ];
  const p = lib.buildPoster(units, { width: 200, pad: 10 });
  assert.deepEqual(
    p.regions.map((r) => r.id),
    ["fr:reg:11", "fr:reg:76"],
  );
  // The tiny island is dropped; one ring each.
  for (const r of p.regions) assert.equal(r.d.match(/M/g)?.length, 1);
  // North up: the first région's move is above the second's.
  const y = (d: string) => Number(/^M\d+ (\d+)/.exec(d)![1]);
  assert.ok(y(p.regions[0].d) < y(p.regions[1].d));
  assert.equal(p.viewBox, `0 0 200 ${p.height}`);
  for (const r of p.regions)
    for (const m of r.d.matchAll(/M(\d+) (\d+)/g)) {
      assert.ok(Number(m[1]) >= 0 && Number(m[1]) <= 200);
      assert.ok(Number(m[2]) >= 0 && Number(m[2]) <= p.height);
    }
});

test("the generated module is small, has the thirteen régions and is the build's", () => {
  const text = readFileSync(
    new URL("../../../apps/web/src/shared/ui/francePoster.ts", import.meta.url),
    "utf8",
  );
  const lock = JSON.parse(
    readFileSync(new URL("../../../apps/web/outlines.lock.json", import.meta.url), "utf8"),
  ) as { build: string };
  assert.ok(text.startsWith("// GENERATED by scripts/map-data/poster/build.ts"));
  assert.ok(text.includes(`Outline build ${lock.build}`), "regenerate after a lock bump");
  assert.ok(text.length < 16_000, `${text.length} bytes`);
  const ids = [...text.matchAll(/id: "(fr:reg:\d+)"/g)].map((m) => m[1]);
  assert.deepEqual(ids, [...lib.METRO_REGIONS]);
  for (const d of text.matchAll(/ d: "([^"]*)"/g))
    assert.match(d[1], /^(M\d+ \d+(l-?\d+[ -]?-?\d+)+z)+$/);
});
