import { AsyncLocalStorage } from "node:async_hooks";
import type { FastifyRequest } from "fastify";
import { adminClient } from "../supabase";

// EMAIL_MODE=outbox (staging, local development): no email leaves, each one
// is kept in captured_emails and shown on the site's test outbox, tagged with
// whoever's action sent it — the browser (its random X-Outbox-Viewer id) and
// the signed-in user — so that a tester finds there what they just did.

interface Acting {
  /** The request being served, read when an email is kept: its user is only known once authenticated. */
  req?: FastifyRequest;
  /** "api", or "auth:<type>" for Supabase Auth's emails (the Send Email hook). */
  source?: string;
  /** The user the email is about, when the request has no signed-in user (the hook). */
  userId?: string;
}

const acting = new AsyncLocalStorage<Acting>();

/** Run `fn` (the rest of a request) with `actor` known to the emails it sends. */
export function runActing<T>(actor: Acting, fn: () => T): T {
  return acting.run({ ...acting.getStore(), ...actor }, fn);
}

/** A browser's outbox id: random, generated by the site (see the web's outbox). */
const VIEWER = /^[A-Za-z0-9-]{8,64}$/;

function viewerOf(req: FastifyRequest | undefined): string | null {
  const header = req?.headers["x-outbox-viewer"];
  return typeof header === "string" && VIEWER.test(header) ? header : null;
}

/** An email is kept 30 days, then goes at the next one kept. */
const KEEP_MS = 30 * 24 * 3600 * 1000;

export interface Capturable {
  to: string | string[];
  subject: string;
  [field: string]: unknown;
}

/** Keep `emails` in the outbox instead of sending them; their ids, in order. */
export async function captureEmails(emails: Capturable[]): Promise<string[]> {
  const actor = acting.getStore() ?? {};
  const viewer = viewerOf(actor.req);
  const userId = actor.userId ?? actor.req?.user?.id ?? null;
  const rows = emails.map((e) => ({
    source: actor.source ?? "api",
    recipients: [e.to, e.cc, e.bcc].flatMap((r) =>
      r === undefined ? [] : ([] as string[]).concat(r as string | string[]),
    ),
    subject: e.subject,
    body_html: typeof e.html === "string" ? e.html : null,
    body_text: typeof e.text === "string" ? e.text : null,
    viewer,
    user_id: userId,
  }));
  const { data, error } = await adminClient.from("captured_emails").insert(rows).select("id");
  if (error) throw new Error(`outbox: ${error.message}`);
  const cutoff = new Date(Date.now() - KEEP_MS).toISOString();
  await adminClient.from("captured_emails").delete().lt("created_at", cutoff);
  return data.map((r) => r.id);
}
